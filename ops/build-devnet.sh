from pathlib import Path
p=json.loads(Path('ops/devnet-profile.json').read_text());artifacts={}
local=['Egn8THHpn7AxDMZKgBKui5YTdTcwn2wxwXkFuKzDDbKo','7Kp4Y5yeBiuS9NYmw67quMLRto5Y9CcUQ29VjLviHggU','F3ETRB1fPHjJ2KQYuL8SomC1auBpWK5VtVqFwAU7k2Yc','A5ACpHNQHLkCQtfvRkPoR45juvuxwfi9mEWGU43eD5nj']
mapping=dict(zip(p['programs'].values(),local))
def normalized(value):
    if isinstance(value,dict): return {k:normalized(v) for k,v in value.items() if k!='docs'}
    if isinstance(value,list): return [normalized(v) for v in value]
    if isinstance(value,str): return mapping.get(value,value)
    return value
for name,program in p['programs'].items():
    elf=Path('.local/devnet/deploy')/(name+'.so')
    record={'program':program,'elfBytes':str(elf.stat().st_size),'elfSha256':hashlib.sha256(elf.read_bytes()).hexdigest()}
    if name!='oracle_fixture':
        idl=Path('.local/devnet/idl')/(name+'.json');doc=json.loads(idl.read_text());assert doc['address']==program
        assert normalized(doc)==normalized(json.loads(Path('packages/sdk/idl/'+name+'.json').read_text())), 'Unexpected SDK ABI change'
        record['idlSha256']=hashlib.sha256(idl.read_bytes()).hexdigest()
        record['sdkAbiParity']='exact after declared deployment-address mapping and documentation exclusion'
    artifacts[name]=record
report={'revision':subprocess.check_output(['git','rev-parse','HEAD'],text=True).strip(),'sourceDirty':bool(subprocess.check_output(['git','status','--porcelain'],text=True).strip()),'profile':p,'artifacts':artifacts,'deployed':False}
Path('.local/devnet/build.json').write_text(json.dumps(report,indent=2)+'\n')
print('Devnet SBF/IDL build complete; not deployed')
PY
