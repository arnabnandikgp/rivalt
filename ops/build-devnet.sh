#!/usr/bin/env bash
set -euo pipefail
cd "$(dirname "$0")/.."
source ops/env.sh
test "$(node --version)" = "v24.22.0"
test "$(anchor --version)" = "anchor-cli 1.2.1"
[[ "$(solana --version)" == "solana-cli 4.1.2 "* ]]
export CARGO_PROFILE_TEST_DEBUG=0 CARGO_PROFILE_DEV_DEBUG=0 CARGO_INCREMENTAL=0
umask 077
mkdir -p .local/devnet/deploy .local/devnet/idl
python3 - <<'PY'
import json,subprocess,shutil
from pathlib import Path
p=json.loads(Path('ops/devnet-profile.json').read_text())
for name,role in [('clearing','clearing'),('maker_a','maker-a'),('maker_b','maker-b'),('oracle_fixture','guard')]:
    path=Path('.local/devnet/keys')/(role+'.json')
    # Reviewers can compile the public pinned IDs without deployment secrets.
    # Any keypair generated by build-sbf when these are absent is not a deploy key.
    if path.exists():
        assert path.stat().st_mode & 0o077 == 0, 'Private key permissions'
        assert subprocess.check_output(['solana-keygen','pubkey',str(path)],text=True).strip()==p['programs'][name], 'Devnet key mismatch'
        shutil.copyfile(path,Path('.local/devnet/deploy')/(name+'-keypair.json'))
PY
{
  for path in programs/clearing programs/maker-a programs/maker-b tests/fixtures/oracle; do
    cargo build-sbf --manifest-path "$path/Cargo.toml" --sbf-out-dir "$PWD/.local/devnet/deploy" --tools-version v1.52 --arch v0 -- --locked --features devnet-test-profile
  done
} > .local/devnet/build.log 2>&1
if grep -Eq 'Stack offset .* exceeded|max offset of 4096|overwrites values in the frame' .local/devnet/build.log; then
  echo 'Rejected unsafe SBF stack frame; see .local/devnet/build.log' >&2
  exit 1
elif [[ $? != 1 ]]; then
  echo 'Could not validate SBF stack frames' >&2
  exit 1
fi
for program in clearing maker_a maker_b; do
  NO_DNA=1 anchor idl build -p "$program" -o ".local/devnet/idl/$program.json" -- --locked --features devnet-test-profile >> .local/devnet/build.log 2>&1
done
python3 - <<'PY'
